#!/usr/bin/env python3
"""Generates entities, DAOs and @Database classes for every scenario.

All scenarios store the exact same 10 tables; only the way they are split
across database files changes.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent / "shared/src"
TABLES = 10

# scenario id -> list of (database class, table indexes)
SCENARIOS = {
    "S1": [("MonoDb", list(range(10)))],
    "S2": [("ContactsDb", [0, 1]), ("CalendarDb", list(range(2, 10)))],
    "S5": [(f"FiveDb{i}", [2 * i, 2 * i + 1]) for i in range(5)],
    "S10": [(f"TenDb{i}", [i]) for i in range(10)],
}

HEADER = "// GENERATED by scripts/generate.py - do not edit.\npackage bench\n\n"

common = [HEADER, """import androidx.room3.*
import kotlinx.coroutines.flow.Flow

"""]
for t in range(TABLES):
    common.append(f"""@Entity(tableName = "t{t}")
data class E{t}(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val name: String,
    val value: Long,
    val payload: String,
)

@Dao
interface D{t} {{
    @Insert suspend fun insert(e: E{t}): Long
    @Query("SELECT COUNT(*) FROM t{t}") suspend fun count(): Int
    @Query("SELECT * FROM t{t} ORDER BY id DESC LIMIT 200") suspend fun latest(): List<E{t}>
    @Query("SELECT SUM(LENGTH(payload)) FROM t{t}") suspend fun scan(): Long
    @Query("SELECT COUNT(*) FROM t{t}") fun observeCount(): Flow<Int>
}}

fun D{t}.ops() = TableOps(
    insert = {{ i -> insert(E{t}(name = "n$i", value = i.toLong(), payload = payloadFor(i))) }},
    count = {{ count() }},
    latest = {{ latest().size }},
    scan = {{ scan() }},
    observe = {{ observeCount() }},
)

""")

for sid, dbs in SCENARIOS.items():
    for cls, tables in dbs:
        ents = ", ".join(f"E{t}::class" for t in tables)
        daos = "\n".join(f"    abstract fun d{t}(): D{t}" for t in tables)
        ops = ", ".join(f"d{t}().ops()" for t in tables)
        common.append(f"""@Database(entities = [{ents}], version = 1, exportSchema = false)
@ConstructedBy({cls}Ctor::class)
abstract class {cls} : RoomDatabase() {{
{daos}
    fun handle(path: String) = DbHandle("{cls}", path, this, listOf({ops}))
}}

@Suppress("KotlinNoActualForExpect")
expect object {cls}Ctor : RoomDatabaseConstructor<{cls}> {{
    override fun initialize(): {cls}
}}

expect fun {cls[0].lower() + cls[1:]}Builder(path: String): RoomDatabase.Builder<{cls}>

""")

# Control scenario: 5 databases with a single connection each = 5 connections in total,
# exactly like S1 (1 writer + 4 readers). Isolates "number of databases" from "number of connections".
CONTROL = {"S5c": ("S5", ".setSingleConnectionPool()")}

common.append("val SCENARIOS = listOf(" + ", ".join(f'"{s}"' for s in [*SCENARIOS, *CONTROL]) + ")\n\n")
common.append("fun openScenario(scenario: String, dir: String): List<DbHandle> = when (scenario) {\n")
for sid, dbs in SCENARIOS.items():
    items = ", ".join(
        f'{cls[0].lower() + cls[1:]}Builder("$dir/{cls}.db").configure().build().handle("$dir/{cls}.db")'
        for cls, _ in dbs
    )
    common.append(f'    "{sid}" -> listOf({items})\n')
for cid, (base, extra) in CONTROL.items():
    items = ", ".join(
        f'{cls[0].lower() + cls[1:]}Builder("$dir/{cls}.db").configure(){extra}.build().handle("$dir/{cls}.db")'
        for cls, _ in SCENARIOS[base]
    )
    common.append(f'    "{cid}" -> listOf({items})\n')
common.append('    else -> error("Unknown scenario $scenario")\n}\n')
(ROOT / "commonMain/kotlin/bench/Generated.kt").write_text("".join(common))

for src in ("androidMain", "appleMain", "jvmMain"):
    out = [HEADER, "import androidx.room3.Room\nimport androidx.room3.RoomDatabase\n\n"]
    for dbs in SCENARIOS.values():
        for cls, _ in dbs:
            fn = cls[0].lower() + cls[1:]
            out.append(f"actual fun {fn}Builder(path: String): RoomDatabase.Builder<{cls}> = Room.databaseBuilder<{cls}>(name = path)\n")
    (ROOT / f"{src}/kotlin/bench/Builders.kt").write_text("".join(out))
print("generated")
