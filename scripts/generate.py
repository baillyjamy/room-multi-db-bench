#!/usr/bin/env python3
"""Generates entities, DAOs and @Database classes for every scenario.

All scenarios store the exact same 10 tables; only the way they are split
across database files changes.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent / "shared/src"
TABLES = 10

# scenario id -> list of (database class, table indexes)
SCENARIOS = {
    "S1": [("MonoDb", list(range(10)))],
    "S2": [("ContactsDb", [0, 1]), ("CalendarDb", list(range(2, 10)))],
    "S5": [(f"FiveDb{i}", [2 * i, 2 * i + 1]) for i in range(5)],
    "S10": [(f"TenDb{i}", [i]) for i in range(10)],
}

HEADER = "// GENERATED by scripts/generate.py - do not edit.\npackage bench\n\n"

common = [HEADER, """import androidx.room3.*
import kotlinx.coroutines.flow.Flow

"""]
for t in range(TABLES):
    common.append(f"""@Entity(tableName = "t{t}")
data class E{t}(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val name: String,
    val value: Long,
    val payload: String,
)

@Dao
interface D{t} {{
    @Insert suspend fun insert(e: E{t}): Long
    @Query("SELECT COUNT(*) FROM t{t}") suspend fun count(): Int
    @Query("SELECT * FROM t{t} ORDER BY id DESC LIMIT 200") suspend fun latest(): List<E{t}>
    @Query("SELECT SUM(LENGTH(payload)) FROM t{t}") suspend fun scan(): Long
    @Query("SELECT COUNT(*) FROM t{t}") fun observeCount(): Flow<Int>
}}

fun D{t}.ops() = TableOps(
    insert = {{ i -> insert(E{t}(name = "n$i", value = i.toLong(), payload = payloadFor(i))) }},
    count = {{ count() }},
    latest = {{ latest().size }},
    scan = {{ scan() }},
    observe = {{ observeCount() }},
)

""")

for sid, dbs in SCENARIOS.items():
    for cls, tables in dbs:
        ents = ", ".join(f"E{t}::class" for t in tables)
        daos = "\n".join(f"    abstract fun d{t}(): D{t}" for t in tables)
        ops = ", ".join(f"d{t}().ops()" for t in tables)
        common.append(f"""@Database(entities = [{ents}], version = 1, exportSchema = false)
@ConstructedBy({cls}Ctor::class)
abstract class {cls} : RoomDatabase() {{
{daos}
    fun handle(path: String) = roomHandle("{cls}", path, listOf({ops}))
}}

@Suppress("KotlinNoActualForExpect")
expect object {cls}Ctor : RoomDatabaseConstructor<{cls}> {{
    override fun initialize(): {cls}
}}

expect fun {cls[0].lower() + cls[1:]}Builder(path: String): RoomDatabase.Builder<{cls}>

""")

# Control scenario: 5 databases with a single connection each = 5 connections in total,
# exactly like S1 (1 writer + 4 readers). Isolates "number of databases" from "number of connections".
CONTROL = {"S5c": ("S5", ".setSingleConnectionPool()")}

common.append("val SCENARIOS = listOf(" + ", ".join(f'"{s}"' for s in [*SCENARIOS, *CONTROL]) + ")\n\n")
common.append("fun openScenario(scenario: String, dir: String): List<DbHandle> = when (scenario) {\n")
for sid, dbs in SCENARIOS.items():
    items = ", ".join(
        f'{cls[0].lower() + cls[1:]}Builder("$dir/{cls}.db").configure().build().handle("$dir/{cls}.db")'
        for cls, _ in dbs
    )
    common.append(f'    "{sid}" -> listOf({items})\n')
for cid, (base, extra) in CONTROL.items():
    items = ", ".join(
        f'{cls[0].lower() + cls[1:]}Builder("$dir/{cls}.db").configure(){extra}.build().handle("$dir/{cls}.db")'
        for cls, _ in SCENARIOS[base]
    )
    common.append(f'    "{cid}" -> listOf({items})\n')
common.append('    else -> error("Unknown scenario $scenario")\n}\n')
(ROOT / "commonMain/kotlin/bench/Generated.kt").write_text("".join(common))

for src in ("androidMain", "appleMain", "jvmMain"):
    out = [HEADER, "import androidx.room3.Room\nimport androidx.room3.RoomDatabase\n\n"]
    for dbs in SCENARIOS.values():
        for cls, _ in dbs:
            fn = cls[0].lower() + cls[1:]
            out.append(f"actual fun {fn}Builder(path: String): RoomDatabase.Builder<{cls}> = Room.databaseBuilder<{cls}>(name = path)\n")
    (ROOT / f"{src}/kotlin/bench/Builders.kt").write_text("".join(out))

# ---------- SQLDelight: same tables, same split, official platform drivers ----------
SQ = ROOT.parent / "sqldelight"
for t in range(TABLES):
    d = SQ / "tables"
    d.mkdir(parents=True, exist_ok=True)
    # Same DDL as Room generates for E{t} (autoGenerate = true).
    (d / f"T{t}.sq").write_text(f"""CREATE TABLE t{t} (
    id INTEGER PRIMARY KEY AUTOINCREMENT NOT NULL,
    name TEXT NOT NULL,
    value INTEGER NOT NULL,
    payload TEXT NOT NULL
);

insert:
INSERT INTO t{t}(name, value, payload) VALUES (?, ?, ?);

count:
SELECT COUNT(*) FROM t{t};

latest:
SELECT * FROM t{t} ORDER BY id DESC LIMIT 200;

scan:
SELECT COALESCE(SUM(LENGTH(payload)), 0) FROM t{t};
""")

sq = [HEADER, """import app.cash.sqldelight.coroutines.asFlow
import app.cash.sqldelight.coroutines.mapToOne
import bench.sqldelight.sqHandle
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.IO
import kotlinx.coroutines.flow.map
import kotlinx.coroutines.withContext

"""]
for sid, dbs in SCENARIOS.items():
    for cls, tables in dbs:
        pkg = f"bench.sq.{cls.lower()}"
        for t in tables:
            # insert runs inside writeTx (already on Dispatchers.IO); reads hop to IO like a typical app.
            sq.append(f"""fun {pkg}.T{t}Queries.ops() = TableOps(
    insert = {{ i -> insert("n$i", i.toLong(), payloadFor(i)) }},
    count = {{ withContext(Dispatchers.IO) {{ count().executeAsOne().toInt() }} }},
    latest = {{ withContext(Dispatchers.IO) {{ latest {{ id, name, value_, payload -> E{t}(id, name, value_, payload) }}.executeAsList().size }} }},
    scan = {{ withContext(Dispatchers.IO) {{ scan().executeAsOne() }} }},
    observe = {{ count().asFlow().mapToOne(Dispatchers.IO).map {{ it.toInt() }} }},
)

""")
sq.append("/** SQLDelight has no per-database connection-pool switch comparable to Room's, so S5c is Room-only. */\n")
sq.append("val SQ_SCENARIOS = listOf(" + ", ".join(f'"{s}"' for s in SCENARIOS) + ")\n\n")
sq.append("fun openSqScenario(scenario: String, dir: String): List<DbHandle> = when (scenario) {\n")
for sid, dbs in SCENARIOS.items():
    items = []
    for cls, tables in dbs:
        pkg = f"bench.sq.{cls.lower()}"
        ops = ", ".join(f"db.t{t}Queries.ops()" for t in tables)
        items.append(f'sqHandle("{cls}", "$dir/{cls}.db", {pkg}.Sq{cls}.Schema) {{ d -> {pkg}.Sq{cls}(d).let {{ db -> db to listOf({ops}) }} }}')
    sq.append(f'    "{sid}" -> listOf(\n        ' + ",\n        ".join(items) + ",\n    )\n")
sq.append('    else -> error("Unknown SQLDelight scenario $scenario")\n}\n')
(ROOT / "commonMain/kotlin/bench/GeneratedSq.kt").write_text("".join(sq))

# Large suite adapters: L1 and L2 generate the same queries in distinct packages.
CONTACTS_ADAPTER = """fun bench.sq.{pkg}.ContactsQueries.adapt() = SqContacts(
    upsert = {{ c -> upsert(c.id, c.accountId, c.name, c.email, c.phone, c.organization, c.notes) }},
    count = {{ count().executeAsOne() }},
    byEmails = {{ byEmails(it, ::ContactEntity).executeAsList() }},
    search = {{ search(it, ::ContactEntity).executeAsList() }},
)

"""
CALENDAR_ADAPTER = """fun bench.sq.{pkg}.CalendarQueries.adapt() = SqCalendar(
    insertCalendar = {{ c -> insertCalendar(c.id, c.name, c.color) }},
    insertEvent = {{ e -> insertEvent(e.id, e.calendarId, e.uid, e.title, e.location, e.description, e.startMs, e.endMs, e.rrule, e.updatedAt) }},
    insertAttendee = {{ a -> insertAttendee(a.eventId, a.email, a.status.toLong()) }},
    countEvents = {{ countEvents().executeAsOne() }},
    countAttendees = {{ countAttendees().executeAsOne() }},
    eventsInRange = {{ cals, from, to -> eventsInRange(cals, from, to, ::EventEntity).executeAsList() }},
    attendeesInRange = {{ cals, from, to ->
        attendeesInRange(cals, from, to) {{ id, eventId, email, status -> AttendeeEntity(id, eventId, email, status.toInt()) }}.executeAsList()
    }},
    agendaRaw = {{ cals, from, to -> agendaRaw(cals, from, to, ::AgendaRawRow).executeAsList() }},
    deleteAttendeesOf = {{ deleteAttendeesOf(it) }},
    deleteEventsOf = {{ deleteEventsOf(it) }},
)

"""
large = ["// GENERATED by scripts/generate.py - do not edit.\npackage bench.sqldelight\n\nimport bench.large.*\n\n"]
large += [CONTACTS_ADAPTER.format(pkg=p) for p in ("largemono", "largecontacts")]
large += [CALENDAR_ADAPTER.format(pkg=p) for p in ("largemono", "largecalendar")]
(ROOT / "commonMain/kotlin/bench/sqldelight/GeneratedLargeAdapters.kt").write_text("".join(large))

# Gradle database declarations, read by shared/build.gradle.kts: "<database>=<table indexes>".
lines = [f"{cls}={','.join(map(str, tables))}" for dbs in SCENARIOS.values() for cls, tables in dbs]
(ROOT.parent / "sqldelight/databases.txt").write_text("\n".join(lines) + "\n")
print("generated")
