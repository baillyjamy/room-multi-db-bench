// SQLDelight derives the Queries package from the folder of each .sq file, and the same table file is
// reused by several databases: stage a copy per database under build/ in its own package folder.
fun stageSq(db: String, pkg: String, sources: List<File>): File {
    val root = layout.buildDirectory.dir("sqldelight-src/$db").get().asFile
    val target = File(root, pkg.replace('.', '/'))
    root.deleteRecursively()
    target.mkdirs()
    sources.forEach { it.copyTo(File(target, it.name), overwrite = true) }
    return root
}

sqldelight {
    databases {
        // Small suite: one database per file of every scenario (generated by scripts/generate.py).
        file("sqldelight/databases.txt").readLines().filter { it.isNotBlank() }.forEach { line ->
            val (name, tables) = line.split("=")
            val pkg = "bench.sq.${name.lowercase()}"
            create("Sq$name") {
                packageName.set(pkg)
                srcDirs.setFrom(stageSq("Sq$name", pkg, tables.split(",").map { file("sqldelight/tables/T$it.sq") }))
            }
        }
        // Large suite: L1 = everything in one file, L2 = contacts file + calendar file.
        mapOf(
            "SqLargeMono" to listOf("Contacts", "Calendar", "Join"),
            "SqLargeContacts" to listOf("Contacts"),
            "SqLargeCalendar" to listOf("Calendar"),
        ).forEach { (name, files) ->
            val pkg = "bench.sq.${name.removePrefix("Sq").lowercase()}"
            create(name) {
                packageName.set(pkg)
                srcDirs.setFrom(stageSq(name, pkg, files.map { file("sqldelight/large/$it.sq") }))
            }
        }
    }
}

